/**
 * Generate a 12-word mnemonic recovery phrase
 */
export function generateMnemonicPhrase(): string {
  const words: string[] = [];
  for (let i = 0; i < 12; i++) {
    const idx = Math.floor(Math.random() * WORDLIST.length);
    words.push(WORDLIST[idx]);
  }
  return words.join(' ');
}

/**
 * Generate a 24-character alphanumeric recovery key formatted as:
 * BEST-XXXX-XXXX-XXXX-XXXX
 */
export function generateAlphanumericKey(): string {
  const charset = '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  let raw = '';
  for (let i = 0; i < 16; i++) {
    raw += charset[Math.floor(Math.random() * charset.length)];
  }

  return ['BEST', raw.slice(0, 4), raw.slice(4, 8), raw.slice(8, 12), raw.slice(12, 16)].join('-');
}

/**
 * Normalize any user-entered recovery key or mnemonic phrase
 */
export function normalizeRecoveryKey(input: string): string {
  const trimmed = input.trim();
  if (trimmed.includes(' ')) {
    return trimmed.toLowerCase().replace(/\s+/g, ' ');
  }
  return trimmed.toUpperCase().replace(/[^A-Z0-9]/g, '');
}
